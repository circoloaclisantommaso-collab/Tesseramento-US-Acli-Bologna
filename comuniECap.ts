const cleanString = (str: string): string => {
    return str
        .toUpperCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '') // rimuove accenti
        .replace(/\bS\.\s*/g, 'SAN ') // S. Lazzaro -> SAN Lazzaro
        .replace(/\bST\.\s*/g, 'SANTA ')
        .replace(/[^A-Z0-9\s']/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
};

/**
 * Restituisce il CAP associato a un dato comune di residenza.
 * Se il comune ha più CAP (es. Bologna), restituisce il CAP primario predefinito.
 */
export const getCapForComune = (comuneName?: string | null): string => {
    if (!comuneName || typeof comuneName !== 'string') return '';
    const raw = comuneName.trim();
    if (!raw) return '';

    const cleaned = cleanString(raw);
    const alphaOnly = cleaned.replace(/[^A-Z]/g, '');

    // 1. Ricerca esatta nella lista dei comuni dell'Area Metropolitana
    const exactMatch = COMUNI_E_CAP.find(c => c.nome.toUpperCase() === raw.toUpperCase() || cleanString(c.nome) === cleaned);
    if (exactMatch && exactMatch.cap.length > 0) {
        return exactMatch.cap[0];
    }

    // 2. Ricerca flessibile (senza apostrofi/spazi o prefissi) nei comuni dell'Area Metropolitana
    const flexibleMatch = COMUNI_E_CAP.find(c => {
        const cCleaned = cleanString(c.nome);
        const cAlpha = cCleaned.replace(/[^A-Z]/g, '');
        return cAlpha === alphaOnly || cCleaned.startsWith(cleaned) || cleaned.startsWith(cCleaned);
    });
    if (flexibleMatch && flexibleMatch.cap.length > 0) {
        return flexibleMatch.cap[0];
    }

    // 3. Ricerca nei principali altri comuni italiani
    for (const [nome, cap] of Object.entries(ALTRI_COMUNI_E_CAP)) {
        if (nome === raw.toUpperCase() || cleanString(nome) === cleaned) {
            return cap;
        }
    }

    for (const [nome, cap] of Object.entries(ALTRI_COMUNI_E_CAP)) {
        const nomeCleaned = cleanString(nome);
        const nomeAlpha = nomeCleaned.replace(/[^A-Z]/g, '');
        if (nomeAlpha === alphaOnly || nomeCleaned.startsWith(cleaned) || cleaned.startsWith(nomeCleaned)) {
            return cap;
        }
    }

    return '';
};

// Pre-computa la mappa dai CAP ai comuni per una ricerca efficiente
export const capToComuniMap = new Map<string, string[]>();
COMUNI_E_CAP.forEach(comune => {
    comune.cap.forEach(cap => {
        if (!capToComuniMap.has(cap)) {
            capToComuniMap.set(cap, []);
        }
        capToComuniMap.get(cap)?.push(comune.nome);
    });
});
