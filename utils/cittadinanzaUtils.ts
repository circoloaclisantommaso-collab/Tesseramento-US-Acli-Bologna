/**
 * Normalizza il valore della cittadinanza assicurandosi che contenga
 * ESCLUSIVAMENTE il nome dello Stato sovrano (in MAIUSCOLO),
 * convertendo aggettivi, derivazioni, demotici e sinonimi.
 *
 * @param val Stringa con il valore grezzo (es. "italiana", "Rumena", "marocchino", "ITALIA", "ITALIANO")
 * @returns Nome dello Stato in maiuscolo (es. "ITALIA", "ROMANIA", "MAROCCO")
 */
export function normalizeCittadinanza(val: string | null | undefined): string {
    if (!val || typeof val !== 'string') {
        return 'ITALIA';
    }

    let cleaned = val.trim();
    if (!cleaned) {
        return 'ITALIA';
    }

    // Rimuove prefissi o etichette comuni come "cittadinanza:", "nazionalità:", "cittadino:", "cittadinanza"
    cleaned = cleaned
        .replace(/^(cittadinanza|nazionalit[aà]|cittadino|cittadina|naz|stato di cittadinanza)[:\s-]+/i, '')
        .replace(/[()]/g, '')
        .trim();

    const lower = cleaned.toLowerCase();

    // 1. Controllo esatto nella mappa dei demotici/aggettivi/sinonimi
    if (DEMONYM_TO_STATO[lower]) {
        return DEMONYM_TO_STATO[lower];
    }

    // 2. Controllo token per token se contiene parole come "italiana", "rumena", "marocchino", ecc.
    const words = lower.split(/[\s,/-]+/).filter(Boolean);
    for (const w of words) {
        if (DEMONYM_TO_STATO[w]) {
            return DEMONYM_TO_STATO[w];
        }
    }

    // 3. Verifica per sottostringa se c'è un riscontro chiaro (es. "italiana (UE)")
    for (const [demonym, stato] of Object.entries(DEMONYM_TO_STATO)) {
        if (lower.startsWith(demonym) || lower.endsWith(demonym) || lower.includes(` ${demonym} `)) {
            return stato;
        }
    }

    // 4. Se è già un nome di stato o non riconosciuto, restituiscilo in lettere maiuscole pulite
    return cleaned.toUpperCase();
}
